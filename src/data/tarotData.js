export const getTarotByFile = (file) => TAROT_78.find(t=>t.file===file);
export const getTarotByName = (name) => {
  if(!name) return TAROT_78[0];
  const low=name.toLowerCase();
  return TAROT_78.find(t=>t.name.toLowerCase()===low) || TAROT_78.find(t=>low.includes(t.file.toLowerCase().replace('.jpg',''))) || TAROT_78.find(t=>t.name.toLowerCase().includes(low)) || TAROT_78[0];
};
export const getRandomTarot = () => TAROT_78[Math.floor(Math.random()*TAROT_78.length)];
export const getTarotImagePath = (nameOrFile) => {
  if(!nameOrFile) return `${import.meta.env.BASE_URL}tarot/Major00.jpg`;
  if(nameOrFile.includes('.jpg')) return `${import.meta.env.BASE_URL}tarot/${nameOrFile}`;
  return getTarotByName(nameOrFile)?.path || `${import.meta.env.BASE_URL}tarot/Major00.jpg`;
};
